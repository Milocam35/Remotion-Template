// Generates the bone-healing video's voice-over with ElevenLabs: one MP3 per scene + per-word timings.
// Run: npm run voiceover   (loads ELEVENLABS_API_KEY from .env.local)
import { ElevenLabsClient } from "@elevenlabs/elevenlabs-js";
import { mkdirSync, writeFileSync } from "node:fs";

const VOICE = { id: "x5IDPSl4ZUbhosMmVFTk", name: "Lumina" }; // Lumina – Neutral and Clear (Colombian), Voice Library
const FALLBACK = { id: "cgSgspJ2msm6clMCkdW9", name: "Jessica" }; // premade, always available
const MODEL = "eleven_v4";
const SCENES = [
  {
    id: "escena1",
    text: "¿Sabes cómo cura realmente un hueso roto? No siempre ocurre de la misma manera. Todo depende de dos cosas: qué tan juntos quedan los fragmentos y cuánta estabilidad mecánica tienen.",
  },
  { id: "escena2", text: "Esto decide si la consolidación será primaria o secundaria." },
];
const OUT_AUDIO = "public/voiceover/hueso";
const OUT_DATA = "src/hueso/voiceover.gen.ts";

// Groups per-character timings into [word, start, end] in seconds.
const toWords = ({ characters, characterStartTimesSeconds: s, characterEndTimesSeconds: e }) => {
  const words = [];
  let cur = null;
  characters.forEach((ch, i) => {
    if (/\s/.test(ch)) {
      cur = null;
    } else if (cur) {
      cur[0] += ch;
      cur[2] = e[i];
    } else {
      cur = [ch, s[i], e[i]];
      words.push(cur);
    }
  });
  return words.map(([w, a, b]) => [w, +a.toFixed(3), +b.toFixed(3)]);
};

const client = new ElevenLabsClient();
const { voices } = await client.voices.getAll();
// Voice Library voices only work after "Add to my voices" in the ElevenLabs web app.
const mine = voices.find((v) => v.voiceId === VOICE.id || v.name?.startsWith(VOICE.name));
const voice = mine ? { id: mine.voiceId, name: VOICE.name } : FALLBACK;
if (!mine) console.warn(`! ${VOICE.name} is not in your voices yet — using ${FALLBACK.name}. Add it from the Voice Library and run again.`);

mkdirSync(OUT_AUDIO, { recursive: true });
const data = {};
for (const [i, scene] of SCENES.entries()) {
  const res = await client.textToSpeech.convertWithTimestamps(voice.id, {
    text: scene.text,
    modelId: MODEL,
    languageCode: "es",
    voiceSettings: { stability: 0.5, similarityBoost: 0.75 },
    previousText: SCENES[i - 1]?.text, // request stitching keeps tone continuous across scenes
    nextText: SCENES[i + 1]?.text,
    seed: 7,
  });
  if (!res.alignment) throw new Error(`No timings returned for ${scene.id}`);
  writeFileSync(`${OUT_AUDIO}/${scene.id}.mp3`, Buffer.from(res.audioBase64, "base64"));
  const words = toWords(res.alignment);
  data[scene.id] = { file: `voiceover/hueso/${scene.id}.mp3`, voice: voice.name, end: words.at(-1)[2], words };
  console.log(`✓ ${scene.id}: ${data[scene.id].end.toFixed(2)} s, ${words.length} words, voice ${voice.name}`);
}

writeFileSync(
  OUT_DATA,
  `// Generated by scripts/generate-voiceover.mjs — do not edit by hand.\nexport const VOICEOVER = ${JSON.stringify(data, null, 2)} as const;\n`,
);
